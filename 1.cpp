// Задача 1
#include <iostream>
using namespace std;

int main() {
    int n;  // Переменная для хранения размера массива
    
    // Запрашиваем у пользователя размер массива
    cout << "Введите размер массива: ";
    cin >> n;

    // Проверяем корректность размера (должен быть положительным)
    if (n <= 0) {
        cout << "Некорректный размер массива." << endl;
        return 1;  // Завершаем программу с кодом ошибки
    }

    // Выделяем динамическую память под массив из n элементов
    int* arr = new int[n];

    // Заполняем массив: считываем n чисел с клавиатуры
    cout << "Введите " << n << " чисел:" << endl;
    for (int i = 0; i < n; i++) {
        cin >> arr[i];  // Читаем очередное число в i-й элемент
    }

    // Меняем местами первый и последний элементы массива
    int temp = arr[0];      // Сохраняем первый элемент во временную переменную
    arr[0] = arr[n - 1];    // На место первого ставим последний
    arr[n - 1] = temp;      // На место последнего ставим бывший первый

    // Выводим массив после замены
    cout << "Массив после замены: ";
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";  // Печатаем i-й элемент через пробел
    }
    cout << endl;

    // Освобождаем выделенную динамическую память
    delete[] arr;

    return 0;  // Успешное завершение программы
}
